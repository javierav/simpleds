"""Embeds the files in web/ into the firmware.

Each file is gzip-compressed and written as a byte array to
src/generated/web_assets_data.cpp, served with `Content-Encoding: gzip`.
The output is only rewritten when it changes, to avoid needless rebuilds.
"""

import gzip
from pathlib import Path

Import("env")  # noqa: F821  (provided by PlatformIO)

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
}

project_dir = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
web_dir = project_dir / "web"
output = project_dir / "src" / "generated" / "web_assets_data.cpp"


def to_c_array(data: bytes) -> str:
    rows = (", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16))
    return ",\n    ".join(rows)


def generate() -> str:
    arrays, entries = [], []
    files = sorted(p for p in web_dir.rglob("*") if p.is_file() and not p.name.startswith("."))
    for index, path in enumerate(files):
        content_type = CONTENT_TYPES.get(path.suffix)
        if content_type is None:
            raise SystemExit(f"embed_web_assets: unsupported file type: {path}")
        data = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        url = "/" + path.relative_to(web_dir).as_posix()
        arrays.append(f"const uint8_t kAsset{index}[] = {{\n    {to_c_array(data)}\n}};")
        entries.append(f'    {{"{url}", "{content_type}", kAsset{index}, sizeof(kAsset{index})}},')

    return "\n".join(
        [
            "// Generated by scripts/embed_web_assets.py from web/. Do not edit.",
            "",
            '#include "services/web/web_assets.h"',
            "",
            "namespace simpleds::services {",
            "",
            "namespace {",
            *arrays,
            "}  // namespace",
            "",
            "const WebAsset kWebAssets[] = {",
            *entries,
            "};",
            "",
            "const size_t kWebAssetCount = sizeof(kWebAssets) / sizeof(kWebAssets[0]);",
            "",
            "}  // namespace simpleds::services",
            "",
        ]
    )


source = generate()
if not output.exists() or output.read_text() != source:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(source)
    print(f"embed_web_assets: wrote {output.relative_to(project_dir)}")
